"""Prompt templates copied verbatim from docs/prompts.md.

Each prompt N lives in `pNN_<name>.system.txt` and `pNN_<name>.user.txt`,
generated by scripts/sync_prompts.py; edit docs/prompts.md, never these files.
`render()` fills {{variable}} placeholders; it never edits prompt text.
"""

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

_DIR = Path(__file__).parent

# Model ("flash" | "pro") and temperature per prompt, from the table in docs/prompts.md.
CONFIG: dict[str, tuple[str, float]] = {
    "p01_signals": ("flash", 0.1),
    "p02_segments": ("pro", 0.3),
    "p03_personas": ("pro", 0.9),  # also needs {{segment_id}}: it appears in the output template
    "p04_simulate": ("flash", 0.7),
    "p05_focus_group": ("pro", 0.8),
    "p06_insights": ("pro", 0.3),
    "p07_improve": ("pro", 0.6),
    "p08_backtest": ("flash", 0.2),
}
_VAR = re.compile(r"\{\{\s*(\w+)\s*\}\}")


@lru_cache
def _load(filename: str) -> str:
    return (_DIR / filename).read_text(encoding="utf-8")


def _fill(template: str, variables: dict[str, Any]) -> str:
    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in variables:
            raise KeyError(f"Missing prompt variable: {key}")
        v = variables[key]
        if isinstance(v, str):
            return v
        if isinstance(v, float) and v.is_integer():
            return str(int(v))  # ₹{{price_inr}} -> ₹149, not ₹149.0
        return json.dumps(v, ensure_ascii=False)

    return _VAR.sub(sub, template)


def variables(name: str) -> set[str]:
    """Placeholder names a prompt needs, across its system and user templates."""
    return set(_VAR.findall(_load(f"{name}.system.txt") + _load(f"{name}.user.txt")))


def render(name: str, **variables: Any) -> tuple[str, str]:
    """Return (system, user) for prompt `name`, e.g. render("p04_simulate", persona=...)."""
    return _fill(_load(f"{name}.system.txt"), variables), _fill(_load(f"{name}.user.txt"), variables)
